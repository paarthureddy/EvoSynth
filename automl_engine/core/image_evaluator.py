import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import TensorDataset, DataLoader
import numpy as np
import ConfigSpace.hyperparameters as CSH
from ConfigSpace import Configuration
from .search_space import get_image_nas_search_space


class DynamicCNN(nn.Module):
    """
    Parametric Convolutional Neural Network whose topology and layers
    are dynamically constructed based on the latent vector generated by EvoSynth.
    """
    def __init__(self, in_channels, conv1_ch, conv2_ch, fc_units, dropout, activation="relu", num_classes=10):
        super().__init__()
        act_layer = nn.ReLU if activation == "relu" else nn.LeakyReLU

        self.features = nn.Sequential(
            nn.Conv2d(in_channels, conv1_ch, kernel_size=3, padding=1),
            nn.BatchNorm2d(conv1_ch),
            act_layer(),
            nn.MaxPool2d(2),
            nn.Conv2d(conv1_ch, conv2_ch, kernel_size=3, padding=1),
            nn.BatchNorm2d(conv2_ch),
            act_layer(),
            nn.AdaptiveAvgPool2d((2, 2))
        )

        self.classifier = nn.Sequential(
            nn.Flatten(),
            nn.Linear(conv2_ch * 2 * 2, fc_units),
            act_layer(),
            nn.Dropout(p=dropout),
            nn.Linear(fc_units, num_classes)
        )

    def forward(self, x):
        return self.classifier(self.features(x))


class ImageCNNEvaluator:
    """
    Neural Architecture Search (NAS) and Hyperparameter Evaluator for non-tabular vision data.
    Trains and validates dynamic PyTorch CNN models on image classification (Handwritten Digits/MNIST).
    """
    def __init__(self, space=None, epochs=3, batch_size=64, device="cpu"):
        self.space = space or get_image_nas_search_space()
        self.epochs = epochs
        self.batch_size = batch_size
        self.device = torch.device(device if torch.cuda.is_available() and device == "cuda" else "cpu")

        # Load image dataset (8x8 digits scaled to image tensors, zero-latency setup)
        from sklearn.datasets import load_digits
        from sklearn.model_selection import train_test_split

        raw = load_digits()
        X = raw.images[:, np.newaxis, :, :].astype(np.float32) / 16.0  # (N, 1, 8, 8) normalized
        y = raw.target.astype(np.int64)

        X_train, X_val, y_train, y_val = train_test_split(
            X, y, test_size=0.25, random_state=42, stratify=y
        )

        self.train_loader = DataLoader(
            TensorDataset(torch.from_numpy(X_train), torch.from_numpy(y_train)),
            batch_size=self.batch_size,
            shuffle=True
        )
        self.val_loader = DataLoader(
            TensorDataset(torch.from_numpy(X_val), torch.from_numpy(y_val)),
            batch_size=self.batch_size,
            shuffle=False
        )

    def evaluate(self, individual):
        """
        Receives an Individual (continuous [0, 1] vector), decodes it into
        CNN architectural topology and training hyperparameters, trains the model,
        and returns validation accuracy.
        """
        valid_vec = np.copy(individual.vector)
        for i, hp_name in enumerate(list(self.space.keys())):
            hp = self.space.get_hyperparameter(hp_name)
            if isinstance(hp, CSH.CategoricalHyperparameter):
                num_choices = len(hp.choices)
                idx = int(np.floor(valid_vec[i] * num_choices))
                idx = min(idx, num_choices - 1)
                valid_vec[i] = float(idx)

        config = Configuration(self.space, vector=valid_vec)

        conv1_ch = int(config["conv1_channels"])
        conv2_ch = int(config["conv2_channels"])
        fc_units = int(config["fc_units"])
        dropout = float(config["dropout_rate"])
        lr = float(config["learning_rate"])
        opt_name = config["optimizer"]
        activation = config["activation"]

        model = DynamicCNN(
            in_channels=1,
            conv1_ch=conv1_ch,
            conv2_ch=conv2_ch,
            fc_units=fc_units,
            dropout=dropout,
            activation=activation,
            num_classes=10
        ).to(self.device)

        criterion = nn.CrossEntropyLoss()
        if opt_name == "Adam":
            optimizer = optim.Adam(model.parameters(), lr=lr)
        elif opt_name == "RMSprop":
            optimizer = optim.RMSprop(model.parameters(), lr=lr)
        else:
            optimizer = optim.SGD(model.parameters(), lr=lr, momentum=0.9)

        # Train model for fixed epochs
        model.train()
        for _ in range(self.epochs):
            for images, labels in self.train_loader:
                images, labels = images.to(self.device), labels.to(self.device)
                optimizer.zero_grad()
                outputs = model(images)
                loss = criterion(outputs, labels)
                loss.backward()
                optimizer.step()

        # Evaluate on validation set
        model.eval()
        correct = 0
        total = 0
        with torch.no_grad():
            for images, labels in self.val_loader:
                images, labels = images.to(self.device), labels.to(self.device)
                outputs = model(images)
                _, predicted = torch.max(outputs.data, 1)
                total += labels.size(0)
                correct += (predicted == labels).sum().item()

        accuracy = (correct / total) * 100.0 if total > 0 else 0.0
        return float(accuracy)
